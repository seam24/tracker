# Serialization + reporting
# =============================================================================

def state_to_dict(st: MutantState) -> dict[str, Any]:
    """Convert MutantState to JSON-serializable dict."""
    return {
        "info": st.info.raw,
        "file": st.file,
        "active": st.active,
        "current_start": st.current_start,
        "current_end": st.current_end,
        "last_commit": st.last_commit,
        "death_reason": st.death_reason,
        "history": [e.__dict__ for e in st.history],
    }


def print_summary(states: dict[str, MutantState]) -> None:
    """Print a compact run summary to stdout."""
    tracked = sum(1 for s in states.values() if s.history)
    print(f"\nTracked {tracked} mutants with at least one commit.")

    reason_counts: dict[str, int] = {}
    for st in states.values():
        if st.death_reason:
            reason_counts[st.death_reason] = reason_counts.get(st.death_reason, 0) + 1

    print("Death reasons (only 'unparseable' and 'no_mapping' are tracked):")
    for reason, count in sorted(reason_counts.items(), key=lambda x: (-x[1], x[0])):
        print(f"  {reason}: {count}")

    for uid, st in states.items():
        if not st.history:
            continue
        first = st.history[0]
        last = st.history[-1]
        line = (
            f"Mutant {uid} tracked from {first.commit} @ {first.date} "
            f"back to {last.commit} @ {last.date} ({len(st.history)} commits)."
        )
        if st.death_reason:
            line += f" Stopped because: {st.death_reason}."
        print(line)


# =============================================================================
# CLI
# =============================================================================

def parse_args() -> argparse.Namespace:
    """
    Parse CLI arguments.

    Cutoff is selected either by:
    - --since ISO timestamp, or
    - --days N (relative to branch tip), default 365
    """
    parser = argparse.ArgumentParser(description="Track Python mutants backwards through Git history.")
    parser.add_argument("--repo", type=str, required=True, help="Path to the Git repository root.")
    parser.add_argument("--branch", type=str, default="HEAD", help="Branch or commit to start from (default: HEAD).")

    cutoff_group = parser.add_mutually_exclusive_group()
    cutoff_group.add_argument("--days", type=int, default=365, help="Look back this many days from branch tip.")
    cutoff_group.add_argument("--since", type=str, help="Only consider commits after this ISO date/time.")

    parser.add_argument(
        "--mutant-json",
        type=str,
        nargs="+",
        required=True,
        help="One or more JSON files containing mutants.",
    )
    parser.add_argument("--output", type=str, default="mutant_history.json", help="Output JSON file.")
    parser.add_argument("--verbose", action="store_true", help="Enable verbose mapping output from GumTree mapper.")
    parser.add_argument("--log-level", type=str, default="INFO", help="Logging level (DEBUG, INFO, WARNING...).")
    return parser.parse_args()


# =============================================================================
# Main
# =============================================================================

def main() -> None:
    args = parse_args()

    logging.basicConfig(level=getattr(logging, args.log_level.upper(), logging.INFO))
    log = logging.getLogger("mutant-tracker")

    repo = RepoAdapter.open(Path(args.repo))
    head_commit = repo.commit(args.branch)
    head_time = head_commit.committed_datetime
    cutoff = Tracker.compute_cutoff(head_time, days=args.days, since=args.since)

    print("HEAD:", head_commit.hexsha, head_time)
    print("Cutoff:", cutoff)
    print("-" * 80)

    mutants = Tracker.load_mutants(args.mutant_json)
    print(f"Loaded {len(mutants)} mutants from {len(args.mutant_json)} JSON files.")

    tracker = Tracker(repo=repo, mapper=GumTreeMapper(), verbose=args.verbose, logger=log)
    states, _ = tracker.run(branch=args.branch, mutants=mutants, cutoff=cutoff)

    print_summary(states)

    output_path = Path(args.output)
    with output_path.open("w", encoding="utf-8") as f:
        json.dump({uid: state_to_dict(st) for uid, st in states.items()}, f, indent=2)

    print(f"\nSaved mutant history to {output_path}")


if __name__ == "__main__":
    main()
