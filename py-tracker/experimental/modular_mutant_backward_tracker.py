class TextUtils:
    """
    Pure string utilities used by the tracker.

    Notes
    -----
    Coordinates are interpreted as character offsets in the decoded text and
    use half-open interval semantics: [start, end).
    """

    @staticmethod
    def apply_mutant(src: str, start: int, end: int, mutant_value: str) -> str:
        """Return `src` with [start:end) replaced by `mutant_value`."""
        start = max(0, min(start, len(src)))
        end = max(start, min(end, len(src)))
        return src[:start] + mutant_value + src[end:]

    @staticmethod
    def is_parseable_python(src: str) -> bool:
        """Return True iff `src` parses as Python."""
        try:
            ast.parse(src)
            return True
        except SyntaxError:
            return False

    @staticmethod
    def offset_to_line_col(src: str, offset: int) -> tuple[int, int]:
        """
        Convert 0-based character offset into (line, col), both 1-based.
        Lines are split on '\\n'.
        """
        offset = max(0, min(offset, len(src)))
        line = 1
        col = 1
        for i in range(offset):
            if src[i] == "\n":
                line += 1
                col = 1
            else:
                col += 1
        return line, col

    @staticmethod
    def get_line(src: str, line_no: int) -> str:
        """Return line_no (1-based) from src without trailing newline, else ''."""
        lines = src.splitlines()
        if 1 <= line_no <= len(lines):
            return lines[line_no - 1]
        return ""


class DebugView:
    """
    Human-friendly debug rendering of mutation locations.

    This is intentionally isolated so core logic stays pure and testable.
    """

    @staticmethod
    def print_mutation_view(
        *,
        label: str,
        src: str,
        start: int,
        end: int,
        path: str,
        commit_hex: str | None,
        context_lines: int = 2,
    ) -> None:
        """
        Pretty-print the mutation location in `src`:
        - file + commit
        - coords
        - a few context lines
        - underline mutated region with ^^^
        """
        print(f"\n--- {label} ---")
        print(f"file: {path}")
        if commit_hex is not None:
            print(f"commit: {commit_hex}")
        print(f"coords: start={start}, end={end}")

        start = max(0, min(start, len(src)))
        end = max(start, min(end, len(src)))

        start_line, start_col = TextUtils.offset_to_line_col(src, start)
        line_no = start_line

        line_start = max(1, line_no - context_lines)
        line_end = line_no + context_lines

        lines = src.splitlines()
        line_end = min(line_end, len(lines))

        for ln in range(line_start, line_end + 1):
            line_text = TextUtils.get_line(src, ln)
            print(f"{ln:5d} | {line_text}")
            if ln == line_no:
                underline_len = max(1, min(len(line_text) - (start_col - 1), (end - start)))
                prefix_spaces = " " * (start_col - 1)
                carets = "^" * underline_len
                print(f"      | {prefix_spaces}{carets} MUTATED REGION")

        print(f"--- end of {label} ---\n")


