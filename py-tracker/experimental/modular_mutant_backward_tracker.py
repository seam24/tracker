# Mapping interface + GumTree implementation
# =============================================================================

class Mapper(Protocol):
    """
    Abstract interface for propagating a source region across revisions.

    Implementations map a half-open region [start, end) from `src_from`
    (newer) to `src_to` (older).

    Returns
    -------
    (new_start, new_end) on success; None on failure.
    """

    def map_region(
        self,
        *,
        src_from: str,
        src_to: str,
        start: int,
        end: int,
        path: str,
        verbose: bool,
    ) -> Optional[tuple[int, int]]:
        ...


class GumTreeMapper:
    """
    GumTree-based Mapper wrapper using `gumtree_mutant_mapper.map_mutant`.

    Only coordinate mapping is done here. Validation and state updates
    happen in the Tracker.
    """

    def map_region(
        self,
        *,
        src_from: str,
        src_to: str,
        start: int,
        end: int,
        path: str,
        verbose: bool,
    ) -> Optional[tuple[int, int]]:
        mu_step = {
            "mutant_id": "n/a",
            "file": path,
            "mutation_start_pos": start,
            "mutation_end_pos": end,
            "mutant_value": "",  # not needed for mapping coords
        }
        mapped_mutant, new_start, new_end = map_mutant(
            src_from=src_from,
            src_to=src_to,
            mu_info_from=mu_step,
            lang=".py",
            verbose=verbose,
        )
        if mapped_mutant is None:
            return None
        return new_start, new_end


