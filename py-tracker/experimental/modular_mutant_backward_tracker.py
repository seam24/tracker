"""
modular_mutant_backward_tracker.py
=================================

This script is a modular reimplementation of `mutant_backward_tracker.py`.
Its goal is to preserve the original behaviour while improving code structure,
readability, and separation of concerns.

Correctness and validation
--------------------------
The modular version has been tested on the BugsInPy project
`cookiecutter-2b` and produces a `mutant_history.json` file that is
semantically identical to the output generated by
`mutant_backward_tracker.py`. Beyond this case study, the implementation
has not yet been extensively validated and should therefore be used with
appropriate caution.

HEAD handling and assumptions
-----------------------------
This implementation does not currently treat `HEAD` as a special case when
analysing source-code evolution. This design choice is motivated by the
characteristics of the BugsInPy dataset: for several projects in this corpus,
the checked-out buggy version may not correspond exactly to the historical
commit recorded in the repository. Such discrepancies typically occur in the
test suite rather than in the program source.

Since this tracker operates exclusively on program source code when
propagating mutants, these mismatches have not affected correctness in
practice. For all projects inspected so far, the source code at `HEAD` has
been identical to the source code of the corresponding buggy commit.

Limitations and future work
---------------------------
The assumptions described above are specific to the BugsInPy setting and do
not hold universally. In more general workflows—particularly when analysing
arbitrary repositories or when the working directory may contain uncommitted
modifications—explicit handling of `HEAD` would be required to ensure safety
and reproducibility. A future revision should therefore distinguish clean
historical commits from potentially modified working copies and adopt more
robust snapshotting strategies where appropriate.
"""

"""
Mutant History Tracker (single-file, modular, documented)
=========================================================

Purpose
-------
Track *Python source-level mutants* backwards through a Git history,
starting from a branch tip (usually HEAD).

A mutant is defined by:
- file path
- character interval [start, end) in that file at the branch tip
- replacement string `mutant_value`

This tool walks commits from newer → older and attempts to *propagate*
each mutant backwards by mapping its source region across file revisions.
When a file changes, mapping is done using a GumTree-based AST differencer
(via `gumtree_mutant_mapper.map_mutant`). When a file is unchanged, the
mutant coordinates propagate trivially.

High-level workflow
-------------------
1. Load mutant JSON files (assumed to match the chosen branch tip).
2. Initialize per-mutant tracking state at HEAD.
3. Prune mutants that already produce unparsable Python at HEAD.
4. Walk Git history backwards:
   - If file unchanged: keep coordinates.
   - If changed: map region from newer → older.
   - Apply mutant to older file and re-parse to ensure validity.
5. Stop tracking a mutant when propagation fails.
6. Write result JSON (`uid -> state`) to disk.

Design goals
------------
- Single file, but logically modular:
    * CLI and configuration at edges
    * Git access behind RepoAdapter
    * Mapping behind a Mapper interface
    * Core algorithm in Tracker
    * Debug printing isolated in DebugView
- Contracts and invariants documented in docstrings.
- Failures absorbed into state (no crashes due to a single mutant).

Input format (expected)
-----------------------
Each JSON file must contain a list of dicts with at least:
{
  "mutant_id": <str/int>,
  "file": <path string>,
  "mutation_start_pos": <int>,
  "mutation_end_pos": <int>,
  "mutant_value": <string>
}

Output format
-------------
The output JSON is a dict mapping uid -> state dict, where uid = "{file}#{mutant_id}".
"""

