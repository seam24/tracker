# Tracker (core logic)
# =============================================================================

class Tracker:
    """
    Orchestrates backward propagation of mutants through Git history.

    The tracker:
    - loads mutants
    - initializes states at HEAD
    - prunes unparseable mutants at HEAD
    - walks commits and propagates mutants
    - returns final states for serialization/reporting
    """

    def __init__(self, *, repo: RepoAdapter, mapper: Mapper, verbose: bool, logger: logging.Logger):
        self.repo = repo
        self.mapper = mapper
        self.verbose = verbose
        self.log = logger

    # --- loading / setup -----------------------------------------------------

    @staticmethod
    def compute_cutoff(head_time: datetime, *, days: int | None, since: str | None) -> datetime:
        """Compute cutoff datetime from either `since` ISO string or `days` back from head_time."""
        if since:
            return datetime.fromisoformat(since)
        assert days is not None
        return head_time - timedelta(days=days)

    @staticmethod
    def load_mutants(json_paths: list[str]) -> list[MutantInfo]:
        """Load mutants from JSON files into MutantInfo objects."""
        out: list[MutantInfo] = []
        for jp in json_paths:
            p = Path(jp)
            with p.open("r", encoding="utf-8") as f:
                data = json.load(f)
            for m in data:
                out.append(
                    MutantInfo(
                        mutant_id=str(m["mutant_id"]),
                        file=m["file"],
                        mutation_start_pos=int(m["mutation_start_pos"]),
                        mutation_end_pos=int(m["mutation_end_pos"]),
                        mutant_value=m["mutant_value"],
                        raw=m,
                    )
                )
        return out

    def init_states(self, *, mutants: list[MutantInfo], head_commit) -> dict[str, MutantState]:
        """
        Create initial MutantState for each mutant at HEAD.

        If the file does not exist at HEAD, the mutant is immediately inactive.
        """
        states: dict[str, MutantState] = {}
        for mi in mutants:
            src_head = self.repo.file_text(head_commit, mi.file)
            if src_head is None:
                states[mi.uid] = MutantState(info=mi, file=mi.file, active=False)
                continue

            s = mi.mutation_start_pos
            e = mi.mutation_end_pos
            states[mi.uid] = MutantState(
                info=mi,
                file=mi.file,
                active=True,
                current_start=s,
                current_end=e,
                last_commit=head_commit.hexsha,
                history=[
                    HistoryEntry(
                        commit=head_commit.hexsha,
                        date=head_commit.committed_datetime.isoformat(),
                        start_pos=s,
                        end_pos=e,
                    )
                ],
                death_reason=None,
            )
        return states

    def initial_prune_unparseable(self, *, states: dict[str, MutantState], head_commit) -> int:
        """
        Disable mutants that already produce unparsable Python at HEAD.

        Returns the number of mutants deactivated by this pruning step.
        """
        dropped = 0
        for st in states.values():
            if not st.active:
                continue

            src_head = self.repo.file_text(head_commit, st.file)
            if src_head is None:
                st.deactivate(None)
                dropped += 1
                continue

            mi = st.info
            mutated = TextUtils.apply_mutant(src_head, mi.mutation_start_pos, mi.mutation_end_pos, mi.mutant_value)
            if not TextUtils.is_parseable_python(mutated):
                st.deactivate("unparseable")
                dropped += 1
        return dropped

    # --- propagation ---------------------------------------------------------

    def propagate_one_step(
        self,
        *,
        pair: CommitPair,
        st: MutantState,
        src_newer: str,
        src_older: str,
        file_changed: bool,
    ) -> None:
        """
        Attempt to propagate a single mutant one commit backwards.

        Behavior
        --------
        - If file unchanged: coordinates propagate unchanged.
        - If changed: map region using mapper from newer → older.

        After mapping (or trivial propagation), apply the mutant_value to
        the older file and validate parseability. If invalid, deactivate.

        Failure modes (stored in st.death_reason)
        -----------------------------------------
        - "no_mapping"  : mapper returns None
        - "unparseable" : mutated older source fails Python parse
        """
        if not st.active:
            return

        # Fast path: file unchanged -> keep coords
        if not file_changed:
            st.last_commit = pair.older.hexsha
            st.history.append(
                HistoryEntry(
                    commit=pair.older.hexsha,
                    date=pair.older.committed_datetime.isoformat(),
                    start_pos=int(st.current_start),
                    end_pos=int(st.current_end),
                )
            )
            return

        # File changed -> map region
        assert st.current_start is not None and st.current_end is not None
        mapped = self.mapper.map_region(
            src_from=src_newer,
            src_to=src_older,
            start=int(st.current_start),
            end=int(st.current_end),
            path=st.file,
            verbose=self.verbose,
        )
        if mapped is None:
            st.deactivate("no_mapping")
            return

        new_start, new_end = mapped

        # Sanity: applying mutant_value to older must still be parseable Python
        mutated_src_older = TextUtils.apply_mutant(src_older, new_start, new_end, st.info.mutant_value)
        if not TextUtils.is_parseable_python(mutated_src_older):
            st.deactivate("unparseable")
            return

        st.current_start = new_start
        st.current_end = new_end
        st.last_commit = pair.older.hexsha
        st.history.append(
            HistoryEntry(
                commit=pair.older.hexsha,
                date=pair.older.committed_datetime.isoformat(),
                start_pos=new_start,
                end_pos=new_end,
            )
        )

    def run(
        self,
        *,
        branch: str,
        mutants: list[MutantInfo],
        cutoff: datetime,
    ) -> tuple[dict[str, MutantState], Any]:
        """
        Execute full tracking run.

        Returns
        -------
        (states, head_commit)
            states: uid -> MutantState
            head_commit: GitPython commit used as starting point
        """
        head_commit = self.repo.commit(branch)
        states = self.init_states(mutants=mutants, head_commit=head_commit)

        dropped = self.initial_prune_unparseable(states=states, head_commit=head_commit)
        self.log.info("Initial pruning dropped %d mutants (unparseable at HEAD).", dropped)

        # ---------------------------------------------------------------------
        # Mental model:
        #
        # We maintain a sliding window of two commits:
        #   newer (already processed) -> older (candidate)
        #
        # For each active mutant:
        #   - if file unchanged: copy coordinates
        #   - if file changed: map coordinates using GumTree
        #
        # Then we shift the window back by one commit.
        # ---------------------------------------------------------------------

        previous = head_commit  # newer side

        for i, commit in enumerate(self.repo.iter_commits_newest_to_oldest(head_commit.hexsha)):
            if i == 0:
                continue  # HEAD itself
            if commit.committed_datetime < cutoff:
                break

            active_uids = [uid for uid, st in states.items() if st.active]
            if not active_uids:
                self.log.info("No active mutants remain; stopping history walk.")
                break

            older = commit
            newer = previous

            self.log.info("Mapping newer %s -> older %s (%d active mutants)", newer.hexsha, older.hexsha, len(active_uids))

            # Precompute/caches per active file
            active_files = {states[uid].file for uid in active_uids}
            file_changed: dict[str, bool] = {}
            src_newer_cache: dict[str, Optional[str]] = {}
            src_older_cache: dict[str, Optional[str]] = {}

            for path in active_files:
                file_changed[path] = self.repo.file_changed(newer, older, path)
                src_newer_cache[path] = self.repo.file_text(newer, path)
                src_older_cache[path] = self.repo.file_text(older, path)

            pair = CommitPair(
                newer=CommitView(newer.hexsha, newer.committed_datetime),
                older=CommitView(older.hexsha, older.committed_datetime),
            )

            for uid in active_uids:
                st = states[uid]
                path = st.file
                src_newer = src_newer_cache.get(path)
                src_older = src_older_cache.get(path)

                if src_newer is None or src_older is None:
                    st.deactivate(None)
                    continue

                self.propagate_one_step(
                    pair=pair,
                    st=st,
                    src_newer=src_newer,
                    src_older=src_older,
                    file_changed=file_changed[path],
                )

            previous = older

        return states, head_commit


