@dataclass(frozen=True)
class MutantInfo:
    """
    Immutable description of a mutant at the branch tip.

    Coordinates use half-open semantics [start, end) over decoded text.
    The `raw` dict is preserved for output transparency.
    """
    mutant_id: str
    file: str
    mutation_start_pos: int
    mutation_end_pos: int
    mutant_value: str
    raw: dict[str, Any] = field(default_factory=dict)

    @property
    def uid(self) -> str:
        """Global unique id for stable indexing in output."""
        return f"{self.file}#{self.mutant_id}"


@dataclass
class HistoryEntry:
    """
    One successful propagation record.

    `start_pos/end_pos` are coordinates *in that commit's file content*.
    """
    commit: str
    date: str
    start_pos: int
    end_pos: int


@dataclass
class MutantState:
    """
    Mutable tracking state for a single mutant.

    Invariants
    ----------
    - history is ordered newest → oldest.
    - If active is False, the mutant is terminal and must not be propagated.
    - current_start/current_end refer to the last commit in `history`.

    Termination reasons (death_reason)
    ----------------------------------
    - None           : file missing, or unspecified termination
    - "unparseable"  : applying mutant makes Python invalid
    - "no_mapping"   : mapper cannot map region across versions
    """
    info: MutantInfo
    file: str
    active: bool = True
    current_start: Optional[int] = None
    current_end: Optional[int] = None
    last_commit: Optional[str] = None
    history: list[HistoryEntry] = field(default_factory=list)
    death_reason: Optional[str] = None

    def deactivate(self, reason: Optional[str]) -> None:
        """Deactivate this mutant and optionally record a termination reason."""
        self.active = False
        self.death_reason = reason


@dataclass(frozen=True)
class CommitView:
    """Minimal commit metadata passed around by the tracker."""
    hexsha: str
    committed_datetime: datetime


@dataclass(frozen=True)
class CommitPair:
    """Commit window (newer → older) for one propagation step."""
    newer: CommitView
    older: CommitView


