class RepoAdapter:
    """
    Thin wrapper around GitPython providing a stable, minimal API.

    Responsibilities:
    - obtain commit objects
    - read file text at a commit
    - detect whether a file changed between commits
    - iterate commits newest → oldest
    """

    def __init__(self, repo: Repo):
        self.repo = repo

    @classmethod
    def open(cls, repo_path: Path) -> "RepoAdapter":
        return cls(Repo(repo_path))

    def commit(self, rev: str):
        """Return GitPython commit for rev (branch name, tag, or hexsha)."""
        return self.repo.commit(rev)

    def _get_blob(self, commit, path: str):
        """Return blob for `path` in `commit`, or None if it doesn't exist."""
        try:
            return commit.tree / path
        except KeyError:
            return None

    def file_text(self, commit, path: str) -> Optional[str]:
        """
        Return file content for `path` in `commit`, decoded as UTF-8 with replacement.
        Returns None if file doesn't exist.
        """
        blob = self._get_blob(commit, path)
        if blob is None:
            return None
        data = blob.data_stream.read()
        return data.decode("utf-8", errors="replace") if isinstance(data, bytes) else data

    def file_changed(self, newer, older, path: str) -> bool:
        """
        Return True if `path` differs between `newer` and `older`.

        If missing in either commit, treated as changed.
        """
        b_new = self._get_blob(newer, path)
        b_old = self._get_blob(older, path)
        if b_new is None or b_old is None:
            return True
        return b_new.hexsha != b_old.hexsha

    def iter_commits_newest_to_oldest(self, rev: str):
        """Yield commits newest → oldest (GitPython iterator)."""
        return self.repo.iter_commits(rev=rev)


